#Lists

fruits = ["Apple", "Orange", "Banana", "Strawberry"]  

fruits[0] = "Grapes" #changing an item

fruits.insert(1, "Strawberry") #positionng new item

fruits.append("Mango") #add the item at the end

fruits.remove("Orange") #if has duplicats, it removes only the first one

fruits.pop(3) #removes a specific item

del fruits[2] #removes a specific item

fruits.clear() #clears



print(fruits)